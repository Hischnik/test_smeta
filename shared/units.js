/**
 * Короткие формы единиц для таблиц, PDF и мобильных карточек.
 * Полные названия остаются в справочниках и формах.
 */
const SHORT_UNITS = {
  мешок: 'меш.',
  мешка: 'меш.',
  мешков: 'меш.',
  упаковка: 'уп.',
  упаковки: 'уп.',
  упаковок: 'уп.',
  пачка: 'пач.',
  канистра: 'кан.',
  ведро: 'вед.',
  рулон: 'рул.',
  рулона: 'рул.',
  комплект: 'компл.',
  комплекта: 'компл.',
  коробка: 'кор.',
  пакет: 'пак.',
};

export function shortUnit(unit) {
  const value = String(unit ?? '').trim();
  if (!value) return '';
  return SHORT_UNITS[value.toLowerCase()] ?? value;
}
